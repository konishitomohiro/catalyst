// AIへの指示文（例/Docs/3_仕組み.md「AIへの指示文」）。
// AIは用語を見つけるだけ。意味の説明や答えは書かせない（医療で誤った答えは命に関わるため）。
import type { Role } from "./roles";

export function buildDetectionPrompt(args: {
  sender: Role;
  recipient: Role;
  utterance: string;
  context: string;
}): string {
  const { sender, recipient, utterance, context } = args;
  return `あなたは医療・介護の現場の会話を手伝うアシスタントです。
${sender}（話し手）が${recipient}（聞き手）に話した発言を読み、
${recipient}が理解するのに前提知識が必要そうな用語を見つけてください。

対象：
- ${recipient}が知らない可能性が高い専門用語・略語・単位
- 理由・頻度・期間・量など、${sender}の頭の中にある前提がないと意味が分からない語

守ること：
- 発言に出てきた表記のまま、語だけを返す。言い換え・説明・答えは書かない。
- 語ごとに、読みをひらがなで添える（ふりがなに使う）。読み以外は書かない。
- ${recipient}が普通に分かる日常語は返さない。
- 発言の中で、すでに言い換えや説明がある語（例：「〇〇（△△）」の形や、直前に意味が書いてある語）は返さない。
- 見つからなければ空の配列を返す。

これまでの会話（参考。ここからは選ばない）：
${context || "（なし）"}

今回の発言（ここから選ぶ）：
${utterance}`;
}

/**
 * 送り手の確認（伝える前）の指示文。AIは問いと「起こりうる取り違え」だけを返し、根拠や答えは書かない。
 * 2026-11-08：揚げ足取りに聞こえないよう、「分からないかもしれない点」ではなく
 * 「このまま伝えると、受け手が違うことをしてしまう点」だけを探させる（例/Docs/3_仕組み.md）
 */
export function buildPremisePrompt(args: {
  sender: Role;
  recipient: Role;
  message: string;
}): string {
  const { sender, recipient, message } = args;
  return `あなたは医療・介護の現場の連絡を手伝うアシスタントです。
目的は、職種の違う人どうしの伝達ミスを防ぐことです。
${sender}が${recipient}に伝えようとしている文章を読み、
このまま伝えると${recipient}が取り違えて、違うことをしてしまうおそれがある点だけを見つけてください。

取り違えの例：
- 違う量・数・回数で用意する、使う
- 違う時間・タイミング・期間で動く
- 違う物・違う種類を用意する
- 何をすればよいか決められず、動けない
- 数や量が「何によって決まるか」が分からないため、あとで「足りない」「余った」と言われたときに、
  違う量を用意してしまう（例：チューブの本数の決まり方を知らず、追加を頼まれて必要以上に持っていく）

返さないもの：
- 理由や背景が書いていなくても、${recipient}のすることが今もあとも変わらない点（数や量の決まり方は、あとの判断を変えるので返してよい）
- ${recipient}の職種なら、ふつうに分かって動ける点
- 「念のため」の確認、あれば親切という程度の情報、まれな場合への備え
- 文に書いてあることを、そのまま聞き直すだけの点

守ること：
- 点ごとに、文の中の該当する部分（quote：文に出てきた表記のまま、短く）、
  ${recipient}が取り違えそうなこと（risk：「〜と受け取るかもしれない」の形で短く）、
  ${recipient}が聞きたくなる問い（question：「〜？」の形で短く）を返す。
- 根拠・答え・言い換え・説明は書かない。根拠を知っているのは${sender}だけ。
- 多くの文章は、このままで伝わる。取り違えが具体的に思い浮かばなければ、空の配列を返す。迷ったら返さない。
- 返すのは、取り違えたときに困るものから2つまで。

文章：
${message}`;
}
