// AIへの指示文（例/Docs/3_仕組み.md「AIへの指示文」）。
// AIは用語を見つけるだけ。意味の説明や答えは書かせない（医療で誤った答えは命に関わるため）。
import type { Role } from "./roles";
import { MAX_SUMMARY_POINTS } from "./summary";

export function buildDetectionPrompt(args: {
  sender: Role;
  recipient: Role;
  utterance: string;
  context: string;
}): string {
  const { sender, recipient, utterance, context } = args;
  return `あなたは医療・介護の現場の会話を手伝うアシスタントです。
${sender}（話し手）と${recipient}（聞き手）が対面で話しています。

1. 今回の発言を、${sender}と${recipient}のどちらが話したかを決め、speaker に入れる。
   ${sender}なら "sender"、${recipient}なら "recipient"。発言の中身（説明・指示か、質問・返事か）とこれまでの会話の流れから決める。
2. 今回の発言は音声入力の文字です。聞き間違い（例：「30mm」→「30mg」、「2畳」→「2錠」、薬の名前の取り違え）があれば、直した発言を corrected に入れる。
   数字は変えない。文の言い回しは変えない。直すところがなければ、発言をそのまま入れる。
3. ${sender}が話した発言なら、${recipient}が理解するのに前提知識が必要そうな用語を見つける。
   ${recipient}が話した発言なら、terms は空の配列にする。terms は直した発言の表記で返す。

対象：
- ${recipient}が知らない可能性が高い専門用語・略語・単位
- 理由・頻度・期間・量など、${sender}の頭の中にある前提がないと意味が分からない語
- 数や量（〇枚・〇本・〇錠・〇日分・〇mL など）で、その数が何から決まったか（1回にどれだけ・1日に何回・何日分・どこに使うか）が、発言にもこれまでの会話にも出ていないもの。
  ${recipient}が数の決まり方を知らないと、使いすぎたり、足りなくなったり、多すぎる量を用意したりするため。数の部分を発言の表記のまま返す（例：「10枚」）。
  決まり方が発言や会話に出ている数（例：「1日2枚、5日分で10枚」）は返さない。
- 検査・結果（診断）・治療（薬・手術・処置を含む）で、${recipient}がそれを知らないと不安になったり、あとの予定が立てられなかったりするのに、次のことが発言にもこれまでの会話にも出ていないもの。
  - 検査（kind: test）：何のための検査か、何が分かるか
  - 結果・診断（kind: result）：それが何を意味するか（どこが悪いのか、良いのか悪いのか）
  - 治療（kind: treatment）：何のための治療か、どれくらい続くか、次に何をするか
  その検査・結果・治療を指す部分を、発言の表記のまま短く返す（例：「CT」「数値が高い」「抗がん剤」）。
  ${recipient}が医療職なら、ふつうは目的や意味を言わなくても分かるので、返さない。
- 語ごとに種類（kind）を入れる。言葉は word、数や量は amount。

守ること：
- 発言に出てきた表記のまま、語だけを返す。言い換え・説明・答えは書かない。
- 語ごとに、読みをひらがなで添える（ふりがなに使う）。読み以外は書かない。
- ${recipient}が普通に分かる日常語は返さない。
- 発言の中で、すでに言い換えや説明がある語（例：「〇〇（△△）」の形や、直前に意味が書いてある語）は返さない。
- 見つからなければ空の配列を返す。

これまでの会話（参考。ここからは選ばない）：
${context || "（なし）"}

今回の発言（ここから選ぶ）：
${utterance}`;
}

/**
 * 送り手の確認（伝える前）の指示文。AIは問いと「起こりうる取り違え」だけを返し、根拠や答えは書かない。
 * 2026-11-08：揚げ足取りに聞こえないよう、「分からないかもしれない点」ではなく
 * 「このまま伝えると、受け手が違うことをしてしまう点」だけを探させる（例/Docs/3_仕組み.md）
 */
export function buildPremisePrompt(args: {
  sender: Role;
  recipient: Role;
  message: string;
}): string {
  const { sender, recipient, message } = args;
  return `あなたは医療・介護の現場の連絡を手伝うアシスタントです。
目的は、職種の違う人どうしの伝達ミスを防ぐことです。
${sender}が${recipient}に伝えようとしている文章を読み、
このまま伝えると${recipient}が取り違えて、違うことをしてしまうおそれがある点だけを見つけてください。

取り違えの例：
- 違う量・数・回数で用意する、使う
- 違う時間・タイミング・期間で動く
- 違う物・違う種類を用意する
- 何をすればよいか決められず、動けない
- 数や量が「何によって決まるか」が分からないため、あとで「足りない」「余った」と言われたときに、
  違う量を用意してしまう（例：チューブの本数の決まり方を知らず、追加を頼まれて必要以上に持っていく）

返さないもの：
- 理由や背景が書いていなくても、${recipient}のすることが今もあとも変わらない点（数や量の決まり方は、あとの判断を変えるので返してよい）
- ${recipient}の職種なら、ふつうに分かって動ける点
- 「念のため」の確認、あれば親切という程度の情報、まれな場合への備え
- 文に書いてあることを、そのまま聞き直すだけの点

守ること：
- 点ごとに、文の中の該当する部分（quote：文に出てきた表記のまま、短く）、
  ${recipient}が取り違えそうなこと（risk：「〜と受け取るかもしれない」の形で短く）、
  ${recipient}が聞きたくなる問い（question：「〜？」の形で短く）を返す。
- 根拠・答え・言い換え・説明は書かない。根拠を知っているのは${sender}だけ。
- 多くの文章は、このままで伝わる。取り違えが具体的に思い浮かばなければ、空の配列を返す。迷ったら返さない。
- 返すのは、取り違えたときに困るものから2つまで。

文章：
${message}`;
}

/** 履歴の要約：会話全体から、聞いた人（recipient）があとで見返す要約。lines は「職種：発言」の形 */
export function buildSummaryPrompt(args: {
  sender: Role;
  recipient: Role;
  lines: string[];
}): string {
  return [
    `次は、${args.sender}と${args.recipient}が対面で話した会話の文字起こしです。`,
    `${args.recipient}があとで見返すための要約を作ってください。`,
    "",
    "作るもの：",
    "- overview：会話全体で、何について話し、どうすることになったかを1〜2文で。",
    `- points：あとで見返す要点を${MAX_SUMMARY_POINTS}つまで。1行ずつ言い直さず、同じ話題の発言（質問と答えなど）をまとめて1つにする。`,
    "",
    "決まり：",
    "- 会話に出たことだけを書く。会話にない説明・理由・助言・医学的な判断は足さない。",
    "- することや決まり（量・回数・時刻・日付・持ち物・連絡のしかた）を優先する。数や時刻は会話のとおりに書く。",
    `- ${args.recipient}が分かるやさしい言葉で、短く。`,
    "- 要点ごとに、元になった会話の中の言葉（quotes）を1つ以上、会話の表記のまま短く書き写す。職種名は含めない。",
    "- あいさつや雑談だけの会話なら、overview だけを書き、points は空にする。",
    "",
    "会話：",
    ...args.lines.map((l) => `- ${l}`),
  ].join("\n");
}
